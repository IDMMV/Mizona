create or replace function public.mz_can_manage_business(target_business text)
returns boolean language sql stable security definer set search_path=public as $$
  select exists(
    select 1 from public.mz_businesses b
    where b.id=target_business and b.owner_user_id=auth.uid()
  ) or exists(
    select 1 from public.mz_business_members m
    where m.business_id=target_business and m.user_id=auth.uid() and m.status='active'
  ) or exists(
    select 1 from public.mz_business_workers w
    where w.business_id=target_business and w.user_id=auth.uid() and w.status='active'
  );
$$;

do $$ begin
  create policy "business workers read" on public.mz_business_workers for select using (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "business workers write" on public.mz_business_workers for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;

do $$ begin
  create policy "business customers access" on public.mz_business_customers for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "cash sessions access" on public.mz_cash_sessions for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "business sales access" on public.mz_business_sales for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "sale items access" on public.mz_business_sale_items for all using (
    exists(select 1 from public.mz_business_sales s where s.id=sale_id and public.mz_can_manage_business(s.business_id))
  ) with check (
    exists(select 1 from public.mz_business_sales s where s.id=sale_id and public.mz_can_manage_business(s.business_id))
  );
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "business expenses access" on public.mz_business_expenses for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "inventory movements access" on public.mz_inventory_movements for all using (public.mz_can_manage_business(business_id)) with check (public.mz_can_manage_business(business_id));
exception when duplicate_object then null; end $$;

