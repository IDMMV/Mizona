-- MiZona 30.73: operaciones normalizadas de Business
create table if not exists public.mz_business_workers (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  user_id uuid null references auth.users(id) on delete set null,
  local_user_id text null,
  role text not null check (role in ('owner','manager','cashier','cook','waiter')),
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mz_business_customers (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  name text not null,
  phone text default '',
  email text default '',
  visits integer not null default 0,
  total_spent numeric(12,2) not null default 0,
  points integer not null default 0,
  notes text default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mz_cash_sessions (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  user_id uuid null references auth.users(id) on delete set null,
  local_user_id text null,
  opening_amount numeric(12,2) not null default 0,
  counted_amount numeric(12,2),
  expected_amount numeric(12,2),
  difference numeric(12,2),
  status text not null default 'open' check (status in ('open','closed')),
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.mz_business_sales (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  order_id text null,
  customer_id text null references public.mz_business_customers(id) on delete set null,
  cash_session_id text null references public.mz_cash_sessions(id) on delete set null,
  cashier_user_id uuid null references auth.users(id) on delete set null,
  local_cashier_id text null,
  receipt text not null,
  payment_method text not null default 'cash',
  subtotal numeric(12,2) not null default 0,
  tax numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  cash_received numeric(12,2) not null default 0,
  change_amount numeric(12,2) not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mz_business_sale_items (
  id bigint generated by default as identity primary key,
  sale_id text not null references public.mz_business_sales(id) on delete cascade,
  product_id text null references public.mz_products(id) on delete set null,
  name text not null,
  quantity numeric(12,3) not null default 1,
  unit_price numeric(12,2) not null default 0,
  line_total numeric(12,2) not null default 0,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.mz_business_expenses (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  cash_session_id text null references public.mz_cash_sessions(id) on delete set null,
  created_by uuid null references auth.users(id) on delete set null,
  local_created_by text null,
  category text not null default 'Otros',
  description text default '',
  amount numeric(12,2) not null check (amount >= 0),
  payment_method text not null default 'cash',
  receipt_url text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mz_inventory_movements (
  id text primary key,
  business_id text not null references public.mz_businesses(id) on delete cascade,
  product_id text not null references public.mz_products(id) on delete cascade,
  user_id uuid null references auth.users(id) on delete set null,
  local_user_id text null,
  quantity numeric(12,3) not null,
  reason text default '',
  reference_type text default 'manual',
  reference_id text null,
  created_at timestamptz not null default now()
);

create index if not exists mz_workers_business_idx on public.mz_business_workers(business_id);
create index if not exists mz_customers_business_idx on public.mz_business_customers(business_id);
create index if not exists mz_cash_business_idx on public.mz_cash_sessions(business_id, status);
create index if not exists mz_sales_business_idx on public.mz_business_sales(business_id, created_at desc);
create index if not exists mz_expenses_business_idx on public.mz_business_expenses(business_id, created_at desc);
create index if not exists mz_inventory_business_idx on public.mz_inventory_movements(business_id, created_at desc);

